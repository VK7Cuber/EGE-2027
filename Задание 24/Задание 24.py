# Способ 4. Регулярные выражения
from re import *

pattern = r'[ABCEF]+' # Регулярное выражение.
                      # В данном случае это строка, в которой одна из букв A, B, C, E, F есть хотя бы один раз
k_max = ""
for x in finditer(pattern, s):
    # x # - это найденная подстрока, но в объекте типа Match
    # x.span() # - получение кортежа с координатами найденной подстроки
    # x.group() # - получение самой найденной подстроки
    substring = x.group()
    k_max = max(k_max, substring, key=len)
print(len(k_max))






















