def f(x, y):
    """
    Функция для поиска количества способов получения числа y из числа x
    :param x: число, с которого начинаем
    :param y: число, которое должны получить
    :return: количество способов
    """
    if x > y or x == "число, которое нужно исключить": return 0
    if x == y: return 1
    return f(x+1, y) + f(x+2, y)
