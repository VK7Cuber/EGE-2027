# Сколько существует программ, для которых при исходном числе 3 результатом является число 75 и при этом траектория вычислений содержит число 25?
def f_3(x, y):
    if x > y: return 0
    if x == y: return 1
    if x % 2 == 0:
        return f_3(x+1, y) + f_3(x+(x+1), y) + f_3(x * 2, y)
    else:
        return f_3(x+1, y) + f_3(x+(x+2), y) + f_3(x * 2, y)
print(f_3(3, 25) * f_3(25, 75))

