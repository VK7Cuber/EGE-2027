# Задача:
# Откройте файл электронной таблицы, содержащей в каждой строке шесть натуральных чисел.
# Определите количество строк таблицы, состоящих из чисел, для которых выполнены оба условия:
# - в строке только одно число повторяется трижды, остальные числа различны;
# - куб повторяющегося числа строки меньше произведения всех её неповторяющихся чисел.
# В ответе запишите только число.
# Ответ - 179

# ШАБЛОН
f = open("9_example.csv")
k = 0

for line in f:
    s = [int(val) for val in line.split(";")] # <- здесь важно проверять, какой у нас разделитель!
    # ИЛИ: s = list(map(int, line.split(";")))
    povtor_3 = [el for el in s if s.count(el) == 3]
    ne_povtor = [el for el in s if s.count(el) == 1]

    if len(set(povtor_3)) == 1 and len(ne_povtor) == 3 \
            and (povtor_3[0]**3) < (ne_povtor[0]*ne_povtor[1]*ne_povtor[2]):
        k += 1
print(k)

