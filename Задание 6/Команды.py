from turtle import *

fd(5) # forward - вперёд на пять
lt(90) # left turn - повернуть направо на 90 градусов
rt(90) # right turn - повернуть направо на 90 градусов
tracer(False) # команда для того, чтобы убрать анимацию и сразу увидеть результат
speed(0) # команда для ускорения процесса построения, но проще просто выклюючить анимацию через tracer()
screensize(5000, 5000) # установка размера просматриваемой рабочей области
penup() # поднять хвост (перо) - отключить рисонвание
penup() # опустить хвост (перо) - начать рисовать
goto(50, 100) # функция для перемещения черепашки в точку по координатам. "Телепортация", при перемещении линий
                    # не остаётся
dot(size=5) # поставить точку в данной координате
done() # Важно! Команда для сохранения построенного чертежа


